import React, { type ReactNode, useRef, useState, useLayoutEffect } from "react";
import { Cpu, FileText, Sparkles, Upload, X, MessageSquare, Tag, Layers, Pencil, GitFork, BookOpen, Info } from "lucide-react";
import { CANVAS, LAYOUT, TYPE } from "../utils/design-tokens";
import { openImageInNewTab } from "../utils/open-image-viewer";

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

/**
 * Display-only meta type that unifies VariationMeta and SnapshotGenerationMeta
 * so a single panel can render generation info from both card and snapshot contexts.
 */
export interface GenerationDetailsMeta {
  prompt?: string;
  model?: string;
  agent?: string;
  userInput?: string;
  generationTime?: number;
  ingredients?: string[];
  paletteImageDataUrl?: string;
  /** All URLs are guaranteed to be non-empty strings. */
  referenceImageUrls?: string[];
  /** Human-readable labels for all selected elements (including non-visual ones). */
  selectedElementLabels?: string[];
  /** Set when this variation was created by the user editing another variation. */
  editedFromLabel?: string;
  /** Distinguishes user-uploaded variations from AI-generated ones. */
  source?: "user-upload";
  /** Add variation 来源类型 */
  addVariationSource?: "from-variation" | "original-brand";
  /** 当 addVariationSource 为 from-variation 时，来源 variation 的 id */
  sourceVariationId?: string;
}

export interface GenerationDetailsPanelProps {
  meta?: GenerationDetailsMeta | null;
  onClose?: () => void;
  /** Shown when meta is null/undefined (e.g. "Generated by Brand Brew AI"). */
  emptyMessage?: ReactNode;
  /** Max height for scrollable body (optional cap; viewport limit applied automatically). */
  maxBodyHeight?: number;
  /** Min gap in px between panel bottom and window bottom (default 16). */
  bottomPadding?: number;
}

// ---------------------------------------------------------------------------
// Internal sub-components
// ---------------------------------------------------------------------------

interface DetailRowProps {
  icon: React.ElementType;
  label: string;
  children: ReactNode;
}

function DetailRow({ icon: Icon, label, children }: DetailRowProps) {
  return (
    <div className="flex items-start gap-2">
      <Icon size={TYPE.icon.sm} className="text-muted-foreground/50 mt-0.5 shrink-0" />
      <div className="min-w-0 flex-1">
        <p className="text-[9px] uppercase tracking-widest text-muted-foreground/50 mb-0.5">
          {label}
        </p>
        {children}
      </div>
    </div>
  );
}

function EmptyValue() {
  return <span className="text-[11px] text-muted-foreground/25 select-none">—</span>;
}

